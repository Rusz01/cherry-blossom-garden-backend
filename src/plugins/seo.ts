import { seoPlugin } from '@payloadcms/plugin-seo'
import type { Field } from 'payload'


const advancedSEOFields: Field[] = [
  {
    name: 'canonicalURL',
    label: 'Canonical URL',
    type: 'text',
    admin: {
      description: 'Leave empty to use this page’s own URL. Set only when the content is duplicated elsewhere.',
    },
    validate: (value: unknown) =>
      !value || /^https?:\/\//.test(String(value)) ? true : 'Use an absolute URL (https://…).',
  },
  {
    type: 'row',
    fields: [
      {
        name: 'noIndex',
        label: 'Hide from search engines (noindex)',
        type: 'checkbox',
        defaultValue: false,
        admin: { width: '50%' },
      },
      {
        name: 'noFollow',
        label: 'Don’t follow links (nofollow)',
        type: 'checkbox',
        defaultValue: false,
        admin: { width: '50%' },
      },
    ],
  },
  {
    name: 'schemaType',
    label: 'Structured data type',
    type: 'select',
    defaultValue: 'WebPage',
    options: [
      { label: 'Web page', value: 'WebPage' },
      { label: 'About page', value: 'AboutPage' },
      { label: 'Contact page', value: 'ContactPage' },
      { label: 'Collection page', value: 'CollectionPage' },
    ],
    admin: { description: 'schema.org type published as JSON-LD for this page.' },
  },
]

/**
 * Page-level SEO via the official Payload SEO plugin (adds an "SEO" tab with
 * live character counters, a search preview and auto-generate buttons),
 * extended with canonical, robots and structured-data controls.
 */
export const seo = () =>
  seoPlugin({
    collections: ['pages'],
    uploadsCollection: 'media',
    tabbedUI: true,
    interfaceName: 'PageMeta',
    generateTitle: ({ doc }) => (doc?.title ? String(doc.title) : ''),
    generateDescription: ({ doc }) => (doc?.excerpt ? String(doc.excerpt).slice(0, 160) : ''),
    generateImage: ({ doc }) => {
      const image = doc?.featuredImage
      return image && typeof image === 'object' ? image.id : image
    },
    // `generateURL` is intentionally omitted: in plugin-seo 3.93 the preview
    // field serialises form state that includes custom array RowLabel
    // components, which throws "Converting circular structure to JSON" in the
    // browser. Canonical URLs are still generated by `src/lib/seo/metadata.ts`.
    fields: ({ defaultFields }) => [...defaultFields, ...advancedSEOFields],
  })
