/**
 * Fill missing CMS fields with the current website defaults.
 * Preserve intentionally empty text and arrays.
 */
export function withDefaults<T>(fallback: T, value: unknown): T {
  if (value === null || value === undefined) return fallback;

  if (Array.isArray(fallback)) {
    if (!Array.isArray(value)) return fallback;

    return value.map((item, index) =>
      withDefaults(
        fallback[Math.min(index, fallback.length - 1)],
        item,
      ),
    ) as T;
  }

  if (
    typeof fallback === "object" &&
    fallback !== null &&
    typeof value === "object" &&
    !Array.isArray(value)
  ) {
    const result: Record<string, unknown> = {};
    const input = value as Record<string, unknown>;

    for (const [key, defaultValue] of Object.entries(fallback)) {
      result[key] = withDefaults(defaultValue, input[key]);
    }

    return result as T;
  }

  return value as T;
}

/**
 * Works with both local static assets and populated Payload uploads.
 */
export function imageSrc(
  value: unknown,
  fallback: string,
): string {
  if (typeof value === "string") {
    return value.startsWith("/") || value.startsWith("https://")
      ? value
      : fallback;
  }

  if (value && typeof value === "object" && "url" in value) {
    const url = (value as { url?: unknown }).url;

    if (typeof url === "string" && url.length > 0) {
      return url;
    }
  }

  return fallback;
}
