/**
 * Generates `src/styles/admin/_nav-icons.scss`: Lucide icons as CSS masks for
 * Payload's sidebar links (which are identified by `#nav-<slug>` ids).
 * Re-run after adding collections/globals: `pnpm generate:nav-icons`.
 */
import { writeFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as icons from 'lucide-react'

const map = {
  'nav-pages': 'FileText',
  'nav-media': 'Image',
  'nav-users': 'Users',
  'nav-roles': 'KeyRound',
  'nav-email-logs': 'MailCheck',
  'nav-payload-jobs': 'Timer',
  'nav-global-site-settings': 'Settings2',
  'nav-global-navigation': 'Menu',
  'nav-global-seo-settings': 'Search',
}

const lines = [
  '// AUTO-GENERATED by scripts/generate-nav-icons.mjs — do not edit by hand.',
  '// Lucide icons (ISC licence) used as CSS masks so they inherit the link colour.',
  '',
]
for (const [id, name] of Object.entries(map)) {
  const svg = renderToStaticMarkup(
    createElement(icons[name], { size: 24, strokeWidth: 1.6, color: '#000', xmlns: 'http://www.w3.org/2000/svg' }),
  )
  const data = Buffer.from(svg).toString('base64')
  lines.push(`#${id}::before { display: block; -webkit-mask-image: url('data:image/svg+xml;base64,${data}'); mask-image: url('data:image/svg+xml;base64,${data}'); }`)
}
writeFileSync('src/styles/admin/_nav-icons.scss', lines.join('\n') + '\n')
console.log(`Generated ${Object.keys(map).length} nav icons.`)
